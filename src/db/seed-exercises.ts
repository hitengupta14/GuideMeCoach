// Muscle group mapping for exercises
const exerciseMuscleMap = buildExerciseMuscleMap()

async function seed() {
  console.log('🌱 Seeding database with 100+ exercises...')

  // Check if data already exists
  const existingExercises = await db.select().from(exercises).limit(1)
  if (existingExercises.length > 0) {
    console.log(`ℹ️  Database already has exercises. Skipping...`)
    return
  }

  // Get muscle groups (created in previous seed)
  const allMuscles = await db.select().from(muscleGroups)
  const muscleMap = Object.fromEntries(allMuscles.map((m) => [m.name, m.id]))

  console.log(`Adding ${exercisesData.length} exercises...`)
  const insertedExercises = await db.insert(exercises).values(exercisesData as any).returning()
  console.log(`✅ Added ${insertedExercises.length} exercises`)

  // Link exercises to muscle groups
  console.log('Linking exercises to muscle groups...')
  let linkCount = 0

  for (const exercise of insertedExercises) {
    const mapping = exerciseMuscleMap[exercise.slug]
    if (!mapping) {
      console.warn(`⚠️  No muscle mapping for ${exercise.name}`)
      continue
    }

    // Primary muscles
    for (const muscle of mapping.primary) {
      if (muscleMap[muscle]) {
        await db.insert(exerciseMuscles).values({
          exerciseId: exercise.id,
          muscleGroupId: muscleMap[muscle],
          role: 'primary',
        })
        linkCount++
      }
    }

    // Secondary muscles
    for (const muscle of mapping.secondary) {
      if (muscleMap[muscle]) {
        await db.insert(exerciseMuscles).values({
          exerciseId: exercise.id,
          muscleGroupId: muscleMap[muscle],
          role: 'secondary',
        })
        linkCount++
      }
    }

    // Stabilizer muscles
    for (const muscle of mapping.stabilizer) {
      if (muscleMap[muscle]) {
        await db.insert(exerciseMuscles).values({
          exerciseId: exercise.id,
          muscleGroupId: muscleMap[muscle],
          role: 'stabilizer',
        })
        linkCount++
      }
    }
  }

  console.log(`✅ Created ${linkCount} exercise-muscle relationships`)
  console.log('✅ Database seeded successfully with 100+ exercises!')
}

seed()
  .catch((error) => {
    console.error('❌ Seeding failed:', error)
    process.exit(1)
  })
  .finally(() => {
    process.exit(0)
  })
